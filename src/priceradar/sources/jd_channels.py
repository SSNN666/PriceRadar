# 路由不出品类时的兜底频道（综合类，实测覆盖最杂）
FALLBACK_CHANNELS: tuple[int, ...] = (2, 33, 23)

DEFAULT_MAX_CHANNELS = 3
_CHINESE = re.compile(r"[一-鿿]+")


def detect_categories(keyword: str) -> list[str]:
    """识别查询涉及的品类（按触发词命中；可多个，保持 CATEGORY_CHANNELS 的顺序）。"""
    text = keyword.lower()
    hit = [
        category
        for category, triggers in CATEGORY_TRIGGERS.items()
        if any(trigger.lower() in text for trigger in triggers)
    ]
    # 保持 CATEGORY_CHANNELS 的声明顺序，使路由结果稳定可复现
    order = list(CATEGORY_CHANNELS)
    return sorted(hit, key=order.index)


def route_channels(keyword: str, *, max_channels: int = DEFAULT_MAX_CHANNELS) -> list[int]:
    """查询 → 频道 ID 列表（去重保序；识别不出品类时走兜底频道）。"""
    channels: list[int] = []
    for category in detect_categories(keyword):
        for channel in CATEGORY_CHANNELS[category]:
            if channel not in channels:
                channels.append(channel)
    if not channels:
        channels = list(FALLBACK_CHANNELS)
    return channels[:max_channels]


def relax_tokens(keyword: str) -> list[str]:
    """放宽匹配用的候选词。

    精确子串匹配不中时的退路——实测「降噪耳机」0 条，但「蓝牙耳机」23 条，
    说明问题在查询词过具体而非频道没货。中文名词通常**落在词尾**
    （"降噪耳机"→"耳机"），故取尾 2 字作为兜底候选。
    """
    tokens = [token for token in re.split(r"[\s·/|,，]+", keyword.strip()) if len(token) >= 2]
    for chunk in _CHINESE.findall(keyword):
        if len(chunk) >= 2:
            tail = chunk[-2:]
            if tail not in tokens:
                tokens.append(tail)
    return tokens
